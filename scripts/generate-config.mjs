#!/usr/bin/env node
// Writes js/config.js (the Firebase web config the browser imports) from
// environment variables, falling back to the .env file in the project root.
//
//   node scripts/generate-config.mjs
//
// Real environment variables win over .env, so CI can inject values from
// repository secrets without needing a .env file. js/config.js may be committed
// (Firebase web config is public); the Pages workflow uses the committed copy
// when no secrets are set.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envFile = join(root, ".env");
const outFile = join(root, "js", "config.js");

// Firebase config key -> environment variable name
const REQUIRED = {
  apiKey: "FIREBASE_API_KEY",
  authDomain: "FIREBASE_AUTH_DOMAIN",
  projectId: "FIREBASE_PROJECT_ID",
  storageBucket: "FIREBASE_STORAGE_BUCKET",
  messagingSenderId: "FIREBASE_MESSAGING_SENDER_ID",
  appId: "FIREBASE_APP_ID",
};
const OPTIONAL = {
  databaseURL: "FIREBASE_DATABASE_URL", // Realtime Database only; this app uses Firestore
  measurementId: "FIREBASE_MEASUREMENT_ID",
};

function parseEnv(text) {
  const vars = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const m = line.match(/^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!m) continue;
    let value = m[2].trim();
    const quote = value[0];
    if ((quote === '"' || quote === "'") && value.length >= 2 && value.endsWith(quote)) {
      value = value.slice(1, -1);
    } else {
      value = value.replace(/\s+#.*$/, ""); // trailing comment on an unquoted value
    }
    vars[m[1]] = value;
  }
  return vars;
}

const fileVars = existsSync(envFile) ? parseEnv(readFileSync(envFile, "utf8")) : {};

function read(name) {
  const value = (process.env[name] || fileVars[name] || "").trim();
  return value === "REPLACE_ME" ? "" : value;
}

const config = {};
const missing = [];
for (const [key, name] of Object.entries(REQUIRED)) {
  const value = read(name);
  if (value) config[key] = value;
  else missing.push(name);
}

if (missing.length) {
  console.error(`Missing Firebase settings: ${missing.join(", ")}`);
  console.error(
    existsSync(envFile)
      ? "Fill them in .env (see .env.example), then run this script again."
      : "No .env file found. Copy .env.example to .env, fill it in, then run this script again."
  );
  process.exit(1);
}

for (const [key, name] of Object.entries(OPTIONAL)) {
  const value = read(name);
  if (value) config[key] = value;
}

const fields = Object.entries(config)
  .map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`)
  .join("\n");

writeFileSync(
  outFile,
  `// AUTO-GENERATED by scripts/generate-config.mjs from .env - do not edit by hand.
// Re-run \`node scripts/generate-config.mjs\` after changing .env.

export const FIREBASE_CONFIG = {
${fields}
};
`
);

console.log(`Wrote js/config.js for Firebase project "${config.projectId}".`);
